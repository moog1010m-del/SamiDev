"""Generate a versioned, public-static-only cache contract from actual file bytes."""
from pathlib import Path
import hashlib,json
from urllib.parse import urlsplit
ROOT=Path(__file__).resolve().parents[1]
GAME=ROOT/'game'
def build():
    runtime=json.loads((GAME/'runtime-games.json').read_text())
    groups={}; files={}
    def add(paths,path):
        path=urlsplit(path).path
        local=GAME/path.lstrip('/')
        if path=='/client-config.js' or not local.is_file() or local.suffix=='.html':return
        files[path]=hashlib.sha256(local.read_bytes()).hexdigest();paths.add(path)
    for key,data in runtime.items():
        paths=set();base=GAME/data['root'].lstrip('/')
        for path in ['game-bootstrap.js','runtime-games.json','samidev-integrity.json']:
            add(paths,'/'+path)
        for path in data['scripts']+data['styles']:
            add(paths,path if path.startswith('/') else data['root']+path)
        for path in ['main.js','__assets.json']+data['images']:
            add(paths,data['root']+path)
        for path in json.loads((base/'__assets.json').read_text()):
            add(paths,data['root']+path.removeprefix(key+'/'))
        # Shared themes and the branded Uno felt used by the runtime.
        for path in ['/images/themes/pool-emerald.webp','/images/cues/moon.webp','/games/crazy8/images/samidev-uno-felt.png']:
            add(paths,path)
        if key=='pool':
            for asset in (GAME/'images/pool-large').glob('*.webp'):
                add(paths,'/'+asset.relative_to(GAME).as_posix())
            for path in ['/images/effects/plazr-water.webp','/images/effects/plazr-water-preview.webp','/sounds/plazr-water-wave.wav','/images/themes/plazr-engraving.webp']:
                add(paths,path)
        groups[key]=sorted(paths)
    config={'files':files,'groups':groups}
    version=hashlib.sha256(json.dumps(config,sort_keys=True).encode()).hexdigest()[:20]
    source=(ROOT/'tools/asset-worker.template.js').read_text()
    (GAME/'asset-worker.js').write_text('/* Generated by tools/build_asset_cache.py. */\nconst CONTRACT='+json.dumps(config,separators=(',',':'))+';\nconst VERSION='+json.dumps(version)+';\n'+source)
    return version
if __name__=='__main__':print(build())
