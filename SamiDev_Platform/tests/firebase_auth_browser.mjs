import assert from 'node:assert/strict';
import fs from 'node:fs';
const {chromium}=await import(process.env.SAMIDEV_PLAYWRIGHT_MODULE||'playwright-core');
const base=process.env.SAMIDEV_TEST_BASE_URL;
assert(['127.0.0.1','localhost'].includes(new URL(base).hostname));
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']});
try {
  const page=await browser.newPage({viewport:{width:390,height:844}}), errors=[],google=[];
  page.on('pageerror',e=>errors.push(e.message));
  let verified=false,newIdentity=false;
  await page.route(/^https:\/\/(identitytoolkit|securetoken)\.googleapis\.com\//, async route=>{
    const request=route.request(),url=new URL(request.url()),refresh=url.hostname==='securetoken.googleapis.com';
    assert.equal(request.method(),'POST');assert.equal(url.searchParams.get('key'),'public-fixture');
    assert(!request.headers().cookie);
    const data=refresh?Object.fromEntries(new URLSearchParams(request.postData())):request.postDataJSON();
    google.push({path:url.pathname,data});
    const token=newIdentity?'fixture-new':verified?'fixture-verified':'fixture-unverified';
    if(refresh){assert.equal(data.grant_type,'refresh_token');assert.equal(data.refresh_token,'fixture-refresh');}
    let body=refresh?{id_token:token,refresh_token:'fixture-refresh'}:{idToken:token,refreshToken:'fixture-refresh'};
    if(url.pathname.endsWith('sendOobCode'))body={email:'browser@example.test'};
    await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(body)});
  });
  await page.goto(base+'/platform/');
  const form=page.locator('#firebase-auth-form');await form.waitFor();
  assert(!await page.locator('#login-form').isVisible());
  await form.locator('[data-mode]').click();
  await form.locator('[name=email]').fill('browser@example.test');
  await form.locator('[name=linkLegacy]').check();
  await form.locator('[name=legacyUsername]').fill('old_browser');
  await form.locator('[name=legacyPassword]').fill('wrong');
  await form.locator('[name=password]').fill('New-password-123456');
  await form.locator('[name=confirmation]').fill('New-password-123456');
  await form.locator('[data-submit]').click();
  await form.locator('[data-resend]').waitFor({state:'visible'});
  assert(google.some(x=>x.data.requestType==='VERIFY_EMAIL'));
  assert(!await form.locator('[name=password]').isVisible());
  await form.locator('[data-submit]').click();
  await page.waitForFunction(()=>document.querySelector('[data-status]').textContent.includes('وثّق'));
  verified=true;
  await form.locator('[data-submit]').click();
  await page.waitForFunction(()=>document.querySelector('[data-status]').textContent.includes('غير صحيحة'));
  assert(await form.isVisible());
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await form.locator('[name=legacyPassword]').fill('Original-password-123');
  await form.locator('[data-submit]').click();
  await page.locator('#app').waitFor({state:'visible'});
  const me=await page.evaluate(()=>fetch('/api/me').then(r=>r.json()));
  assert.equal(me.user.username,'old_browser');
  const cookie=(await page.context().cookies()).find(c=>c.name==='samidev_session');
  assert(cookie.httpOnly);
  assert(!await page.evaluate(()=>JSON.stringify({...localStorage,...sessionStorage}).includes('fixture-')));
  await page.setViewportSize({width:1280,height:900});
  await page.locator('#logout-btn').click();await form.waitFor({state:'visible'});
  await form.locator('[data-reset]').click();
  await page.waitForFunction(()=>document.querySelector('[data-status]').textContent.includes('إذا كان البريد'));
  assert(google.some(x=>x.data.requestType==='PASSWORD_RESET'));
  // Switching out of pending verification must not leave hidden required fields.
  await form.locator('[data-old]').click();await page.locator('#login-form').waitFor();
  await page.getByRole('button',{name:'العودة للدخول بالبريد'}).click();
  assert(await form.locator('[name=password]').isVisible());
  assert(await form.locator('[name=email]').isEditable());
  const out=process.env.SAMIDEV_TEST_ARTIFACTS||'/tmp/samidev-firebase-review';fs.mkdirSync(out,{recursive:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:out+'/email-login-mobile.png',fullPage:true});
  await form.locator('[data-mode]').click();
  await page.screenshot({path:out+'/email-register-mobile.png',fullPage:true});
  // A verified Firebase account without a local profile must choose a username.
  newIdentity=true;
  await form.locator('[data-mode]').click();
  await form.locator('[name=email]').fill('new@example.test');
  await form.locator('[name=password]').fill('New-password-123456');
  await form.locator('[data-submit]').click();
  await form.locator('[data-submit]').filter({hasText:'إكمال الحساب'}).waitFor();
  await form.locator('[name=username]').fill('new_browser');
  await form.locator('[data-submit]').click();
  await page.locator('#app').waitFor({state:'visible'});
  assert.equal((await page.evaluate(()=>fetch('/api/me').then(r=>r.json()))).user.username,'new_browser');
  // Default-off configuration keeps the original login and issues no Google calls.
  await page.context().clearCookies();const googleBefore=google.length;
  await page.route('**/api/auth/config',route=>route.fulfill({contentType:'application/json',body:'{"ok":true,"provider":"local"}'}));
  await page.reload();await page.locator('#login-form').waitFor({state:'visible'});
  assert.equal(await page.locator('#firebase-auth-form').count(),0);assert.equal(google.length,googleBefore);
  await page.unroute('**/api/auth/config');
  await page.route('**/api/auth/config',route=>route.fulfill({status:503,contentType:'application/json',body:'{"ok":false}'}));
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('تعذر تحميل'));
  assert(await page.locator('#login-form button').isDisabled(),'configuration outage must not silently enable legacy login');
  assert.deepEqual(errors,[]);
  console.log('FIREBASE_WEB_PASS: signup, verify, old-account proof retry, logout, reset, fixed Google destinations');
}finally{await browser.close();}
