"""Build the real game manifest with POSIX and Windows path semantics."""
import importlib.util
import json
from pathlib import Path, PurePosixPath, PureWindowsPath
import shutil
import tempfile
import unittest
from unittest.mock import patch
from urllib.parse import urljoin, urlsplit

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("bootstrap_builder", ROOT / "tools/build_game_bootstrap.py")
builder = importlib.util.module_from_spec(spec)
spec.loader.exec_module(builder)
ENTRIES = {
    "carrom": ("index.html", "/"),
    "pool": ("games/pool/index.html", "/games/pool/"),
    "crazy8": ("games/crazy8/index.html", "/games/crazy8/"),
    "tablesoccer": ("games/tablesoccer/index.html", "/games/tablesoccer/"),
}


class BootstrapBuildTest(unittest.TestCase):
    def build_with_paths(self, path_type):
        with tempfile.TemporaryDirectory() as temporary:
            target = Path(temporary)
            for entry, _ in ENTRIES.values():
                destination = target / entry
                destination.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(ROOT / "game" / entry, destination)
            # Keep actual temporary-file I/O native while exercising the path
            # semantics used to derive public URLs on each build machine.
            with patch.object(builder, "ROOT", target), patch.object(builder, "Path", path_type):
                result = builder.build()
            encoded = (target / "runtime-games.json").read_bytes()
        self.assertEqual(json.loads(encoded), result)
        for game, (_, expected_root) in ENTRIES.items():
            with self.subTest(game=game, platform=path_type.__name__):
                data = result[game]
                # This exact root is the browser bootstrap's acceptance contract.
                self.assertEqual(data["root"], expected_root)
                self.assertIsInstance(data["dictionary"], dict)
                self.assertTrue(data["images"])
                self.assertTrue(data["scripts"])
                for resource in data["scripts"] + data["styles"]:
                    url = urlsplit(urljoin("https://game.test" + data["root"], resource))
                    self.assertEqual(url.netloc, "game.test")
                    # This one script is generated by the authenticated server.
                    if url.path != "/client-config.js":
                        self.assertTrue((ROOT / "game" / url.path.lstrip("/")).is_file(), url.path)
        return encoded

    def test_posix_build_matches_browser_resource_contract(self):
        self.build_with_paths(PurePosixPath)

    def test_windows_build_is_identical_to_posix(self):
        self.assertEqual(self.build_with_paths(PureWindowsPath), self.build_with_paths(PurePosixPath))


if __name__ == "__main__":
    unittest.main()
